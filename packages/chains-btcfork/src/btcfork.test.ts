describe('approval / broadcast / status on Dash testnet', () => {
  const tx: BtcForkTx = {
    chainId: DASH_TESTNET,
    from: DASH_SENDER,
    to: DASH_RECIPIENT,
    satoshis: '50000',
    fee: '500',
    inputs: [{ txid: DASH_FUNDING_TXID, vout: 0, previousTxHex: DASH_FUNDING_HEX }],
  };

  it('approves while the input stays unspent', async () => {
    await expect(btcForkApprovalValid(dashAdapter(), tx)).resolves.toBe(true);
  });

  it('refuses approval once the input is gone', async () => {
    const spent = mockAdapter({
      'https://insight.testnet.networks.dash.org/insight-api/status': () => ({
        info: { testnet: true, blocks: 1_573_933 },
      }),
      [`https://insight.testnet.networks.dash.org/insight-api/addr/${DASH_SENDER}/utxo`]: () => [],
    });
    await expect(btcForkApprovalValid(spent, tx)).resolves.toBe(false);
  });

  it('broadcasts the core wire and returns the txid', async () => {
    await expect(
      broadcastBtcFork(dashAdapter(), tx, `0x${'03000000'.padEnd(100, '00')}`),
    ).resolves.toBe(DASH_BROADCAST_TXID);
    await expect(broadcastBtcFork(dashAdapter(), tx, 'beef')).rejects.toThrow('core transaction');
  });

  it('reports confirmation through the insight status endpoint', async () => {
    await expect(btcForkTransferStatus(dashAdapter(), tx, DASH_BROADCAST_TXID)).resolves.toEqual({
      state: 'confirmed',
      blockNumber: 1_570_000,
    });
    await expect(adapter_status_unknown()).resolves.toEqual({ state: 'unknown' });
  });
});

