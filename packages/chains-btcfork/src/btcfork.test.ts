const hexToBytes = (h: string) => Uint8Array.from(h.match(/../g)!.map((b) => parseInt(b, 16)));

describe('addresses', () => {
  it('derives the pinned testnet P2PKH address for every fork', () => {
    for (const [chainId, sender] of Object.entries(TESTNET_SENDERS)) {
      expect(btcforkAddressFromPublicKey(hexToBytes(PUBLIC), chainId), chainId).toBe(sender);
    }
  });

  it('derives the pinned mainnet P2PKH address for every fork', () => {
    for (const [chainId, sender] of Object.entries(MAINNET_SENDERS)) {
      expect(btcforkAddressFromPublicKey(hexToBytes(PUBLIC), chainId), chainId).toBe(sender);
    }
  });

  it('round-trips CashAddr and checks the hrp', () => {
    const hash = hexToBytes(HASH160);
    const addr = cashaddrEncode('bchtest', false, hash);
    expect(addr).toBe(TESTNET_SENDERS[BCH_TESTNET]);
    const decoded = cashaddrDecode(addr);
    expect(decoded?.hrp).toBe('bchtest');
    expect(decoded?.p2sh).toBe(false);
    expect(Buffer.from(decoded!.hash).toString('hex')).toBe(HASH160);
    expect(cashaddrDecode('bchtest:qpumqqygwcnt999fz3gp5nxjy66ckg6esvmzshj479')).toBeUndefined();
    expect(cashaddrDecode('Bchtest:qpumqqygwcnt999fz3gp5nxjy66ckg6esvmzshj478')).toBeUndefined();
  });

  it('validates per-network and rejects other networks', () => {
    for (const [chainId, sender] of Object.entries(TESTNET_SENDERS)) {
      expect(isValidForkAddress(sender, chainId), chainId).toBe(true);
    }
    expect(isValidForkAddress(TESTNET_SENDERS[BCH_TESTNET]!, DASH_TESTNET)).toBe(false);
    expect(isValidForkAddress(TESTNET_SENDERS[DASH_TESTNET]!, DASH_MAINNET)).toBe(false);
    expect(isValidForkAddress(TESTNET_SENDERS[VERUS_TESTNET]!, VERUS_MAINNET)).toBe(true); // shared prefixes
    expect(isValidForkAddress('not-an-address', ZCASH_TESTNET)).toBe(false);
  });

  it('accepts a legacy base58 BCH address alongside CashAddr', () => {
    // 0x6f-prefixed base58check of the same hash160 (generated by the oracle).
    const legacy = decodeForkAddress(BCH_TESTNET, 'mrcNu71ztWjAQA6ww9kHiW3zBWSQidHXTQ');
    expect(legacy?.kind).toBe('p2pkh');
    expect(Buffer.from(legacy!.hash).toString('hex')).toBe(HASH160);
  });
});

describe('funding parser', () => {
  const FUNDING =
    '030000000102020202020202020202020202020202020202020202020202020202020202020100000003515151ffffffff02a0860100000000001976a91479b000887626b294a914501a4cd226b58b23598388ac01000000000000001976a91479b000887626b294a914501a4cd226b58b23598388ac00000000';
  it('parses the pinned funding transaction', () => {
    const out = parseFunding(hexToBytes(FUNDING), 0);
    expect(out.value).toBe(100_000n);
    expect(Buffer.from(out.script).toString('hex')).toBe(`76a914${HASH160}88ac`);
  });
  it('rejects coinbase funding', () => {
    const coinbase =
      '0300000001' + '00'.repeat(32) + 'ffffffff' + '03515151' + 'ffffffff' + '00' + '00000000';
    expect(() => parseFunding(hexToBytes(coinbase), 0)).toThrow('coinbase');
  });
  it('rejects DIP2 special transactions', () => {
    const dip2 = '03000100' + FUNDING.slice(8);
    expect(() => parseFunding(hexToBytes(dip2), 0)).toThrow('DIP2');
  });
  it('rejects a missing output', () => {
    expect(() => parseFunding(hexToBytes(FUNDING), 7)).toThrow('output missing');
  });
});

