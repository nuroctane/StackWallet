/**
 * Regenerates `packages/market/src/chainlink-feeds.ts` from Chainlink's
 * reference data directory (the same JSON data.chain.link serves). Input
 * files are expected under `.nur/chainlink/`; download them first, e.g.
 *
 *   Invoke-WebRequest https://reference-data-directory.vercel.app/feeds-mainnet.json `
 *     -OutFile .nur/chainlink/feeds-mainnet.json
 *
 * Only USD/ETH/BTC-quoted crypto, forex and commodities feeds with a proxy
 * contract are kept; SVR variants, custom/hidden/deprecating feeds and
 * market-hours asset classes (equities, indices) are left out. The output is
 * committed, so builds stay reproducible (D8) and the app fetches nothing.
 * Run from the repo root:
 *
 *   node --experimental-strip-types scripts/sync-chainlink.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'packages/market/src/chainlink-feeds.ts';

const FILES: Record<string, string> = {
  'eip155:1': 'feeds-mainnet.json',
  'eip155:42161': 'feeds-ethereum-mainnet-arbitrum-1.json',
  'eip155:8453': 'feeds-ethereum-mainnet-base-1.json',
  'eip155:10': 'feeds-ethereum-mainnet-optimism-1.json',
  'eip155:137': 'feeds-matic-mainnet.json',
  'eip155:56': 'feeds-bsc-mainnet.json',
  'eip155:43114': 'feeds-avalanche-mainnet.json',
};

const CATEGORY: Record<string, string> = {
  Crypto: 'crypto',
  Forex: 'forex',
  Commodities: 'commodities',
};
const SKIP_CATEGORY = new Set(['custom', 'hidden', 'deprecating']);
const QUOTES = new Set(['USD', 'ETH', 'BTC']);

interface RawFeed {
  name?: string;
  proxyAddress?: string | null;
  contractAddress?: string;
  decimals?: number | null;
  multiply?: string | null;
  heartbeat?: number | null;
  feedType?: string;
  feedCategory?: string;
  svrDisplayLabel?: string | null;
}

interface Kept {
  pair: string;
  base: string;
  quote: string;
  proxy: string;
  decimals: number;
  heartbeatSec: number;
  category: string;
}

function decimalsOf(f: RawFeed): number | null {
  if (typeof f.decimals === 'number' && f.decimals >= 0 && f.decimals <= 36) return f.decimals;
  if (f.multiply && /^\d+$/.test(f.multiply)) {
    const d = f.multiply.length - 1;
    if (/^1[0]*$/.test(f.multiply) && d <= 36) return d;
  }
  return null;
}

const perChain = new Map<string, Kept[]>();
let kept = 0;
let skipped = 0;

for (const [chainId, file] of Object.entries(FILES)) {
  const raw = JSON.parse(readFileSync(`.nur/chainlink/${file}`, 'utf8')) as RawFeed[];
  const byPair = new Map<string, Kept>();
  for (const f of raw) {
    const name = f.name ?? '';
    const parts = name.split(' / ');
    if (parts.length !== 2) {
      skipped += 1;
      continue;
    }
    const [base, quote] = parts as [string, string];
    const category = CATEGORY[f.feedType ?? ''];
    const decimals = decimalsOf(f);
    if (
      !category ||
      !QUOTES.has(quote) ||
      !f.proxyAddress ||
      decimals === null ||
      SKIP_CATEGORY.has(f.feedCategory ?? '') ||
      f.svrDisplayLabel ||
      !/^0x[0-9a-fA-F]{40}$/.test(f.proxyAddress) ||
      !/^[A-Za-z0-9 .'-]{1,24}$/.test(base) ||
      base === quote
    ) {
      skipped += 1;
      continue;
    }
    const pair = `${base} / ${quote}`;
    if (byPair.has(pair)) continue;
    byPair.set(pair, {
      pair,
      base,
      quote,
      proxy: f.proxyAddress.toLowerCase(),
      decimals,
      heartbeatSec: typeof f.heartbeat === 'number' && f.heartbeat > 0 ? f.heartbeat : 0,
      category,
    });
    kept += 1;
  }
  perChain.set(
    chainId,
    [...byPair.values()].sort((a, b) => a.pair.localeCompare(b.pair)),
  );
}

const lines: string[] = [
  '// Generated by scripts/sync-chainlink.ts from the Chainlink reference data',
  '// directory. Do not edit by hand; refresh .nur/chainlink/*.json and rerun.',
  '',
  'export interface ChainlinkFeed {',
  '  /** EVM chain the feed contract lives on. */',
  '  chainId: string;',
  '  /** Display pair, e.g. "ETH / USD". */',
  '  pair: string;',
  '  base: string;',
  '  quote: string;',
  '  /** Aggregator proxy; `latestRoundData` / `getRoundData` are called here. */',
  '  proxy: string;',
  '  decimals: number;',
  '  /** Seconds after which a fresh answer is expected; 0 when undocumented. */',
  '  heartbeatSec: number;',
  "  category: 'crypto' | 'forex' | 'commodities';",
  '}',
  '',
  'export const CHAINLINK_CHAINS: readonly string[] = [',
  ...Object.keys(FILES).map((c) => `  '${c}',`),
  '];',
  '',
  'export const CHAINLINK_FEEDS: readonly ChainlinkFeed[] = [',
];
for (const [chainId, feeds] of perChain) {
  for (const f of feeds) {
    lines.push(
      `  { chainId: '${chainId}', pair: '${f.pair}', base: '${f.base}', quote: '${f.quote}', proxy: '${f.proxy}', decimals: ${f.decimals}, heartbeatSec: ${f.heartbeatSec}, category: '${f.category}' },`,
    );
  }
}
lines.push('];', '');

writeFileSync(OUT, lines.join('\n'));
const counts = [...perChain.entries()].map(([c, f]) => `${c}:${f.length}`).join(' ');
console.log(`wrote ${OUT}: ${kept} feeds kept, ${skipped} skipped (${counts})`);
